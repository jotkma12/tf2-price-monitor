-- Run this in Supabase SQL Editor.
create table if not exists public.tf2_items (
  id bigint generated by default as identity primary key,
  item_name text not null,
  source text not null,
  kind text not null default 'sell' check (kind in ('sell', 'buy_order')),
  item_url text,
  created_at timestamptz not null default now(),
  unique (item_name, source, kind)
);

create table if not exists public.price_observations (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.tf2_items(id) on delete cascade,
  price numeric(18, 6) not null check (price >= 0),
  currency text not null default 'USD',
  observed_at timestamptz not null default now()
);

create index if not exists price_observations_item_time_idx
  on public.price_observations (item_id, observed_at desc);

alter table public.tf2_items enable row level security;
alter table public.price_observations enable row level security;

-- Public website can read data only. Writes are done by GitHub Actions service_role.
drop policy if exists "Public can read TF2 items" on public.tf2_items;
create policy "Public can read TF2 items"
  on public.tf2_items for select using (true);

drop policy if exists "Public can read price observations" on public.price_observations;
create policy "Public can read price observations"
  on public.price_observations for select using (true);

grant select on public.tf2_items to anon, authenticated;
grant select on public.price_observations to anon, authenticated;
